'use strict';
/*
 * One-way sync of the log to a GitHub repository (app -> GitHub).
 *
 * Writes a fixed set of files (CSV tables, a Markdown digest and the full JSON export)
 * as a single commit through GitHub's REST API, using the built-in fetch: no git
 * binary, no npm dependencies. Other files in the target repo (a README, notes) are
 * left untouched. Nothing is ever read back into the app.
 */
const Logic = require('./logic.js');

const FILES = ['digest.md', 'parameters.csv', 'doses.csv', 'maintenance.csv', 'rodi_log.csv', 'filters.csv', 'export.json'];
const REPO_RE = /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/;

/* ------------------------------------------------------------- file builders */
function csvCell(v) {
  if (v == null) return '';
  const s = String(v);
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}
const csv = (header, rows) => [header, ...rows].map((r) => r.map(csvCell).join(',')).join('\n') + '\n';
const byDate = (a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : 0);
const round = (v, dp) => (v == null || isNaN(v) ? null : Number(Number(v).toFixed(dp)));

/** Least-squares slope of value against time, in units per 7 days. null with < 3 points. */
function weeklySlope(pts) {
  if (pts.length < 3) return null;
  const xs = pts.map((p) => Logic.toMs(p.date) / (7 * Logic.DAY)), ys = pts.map((p) => p.v);
  const mx = xs.reduce((a, b) => a + b, 0) / xs.length, my = ys.reduce((a, b) => a + b, 0) / ys.length;
  let num = 0, den = 0;
  xs.forEach((x, i) => { num += (x - mx) * (ys[i] - my); den += (x - mx) ** 2; });
  return den ? num / den : null;
}

function digest(state, today) {
  const cfg = state.config || Logic.DEFAULT_CONFIG;
  const ctx = { config: cfg, entries: state.entries, rodiLogs: state.rodi, today };
  const fmt = (v, dp) => (v == null ? '—' : Logic.fmtNum(v, dp));
  const L = [];
  L.push('# Reef Tracker digest', '');
  L.push(`Data as of ${today}. Generated by the Reef Tracker sync; do not edit (it is overwritten).`, '');
  L.push('Full detail: `parameters.csv` (one row per reading), `doses.csv`, `maintenance.csv` (water changes, GFO, notes), `rodi_log.csv`, `filters.csv`, and `export.json` (complete backup; restore with Settings → Import JSON).', '');

  const alerts = Logic.filterAlerts(ctx, state.filters).filter((a) => a.lvl !== 'info');
  cfg.tanks.forEach((t) => alerts.push(...Logic.paramAlerts(ctx, t.id)));
  L.push('## Alerts', '');
  if (alerts.length) alerts.forEach((a) => L.push(`- ${a.lvl === 'crit' ? '**CRIT**' : 'warn'}: ${a.title} — ${a.detail}`));
  else L.push('- None');
  L.push('');

  cfg.tanks.forEach((t) => {
    const es = state.entries.filter((e) => e.tank === t.id).sort(byDate);
    L.push(`## Tank: ${t.name}`, '');
    L.push(`Type: ${t.kind || 'custom'} · Volume: ${t.volume ? t.volume + ' gal' : 'not set'} · Log entries: ${es.length}` + (es.length ? ` (${es[0].date} to ${es[es.length - 1].date})` : ''), '');
    if (t.params.length) {
      L.push('| Parameter | Latest | Date | Target | Status | 30-day range | 90-day mean | 90-day trend /wk | Tests (90d) |');
      L.push('|---|---|---|---|---|---|---|---|---|');
      const d30 = Logic.msToStr(Logic.toMs(today) - 30 * Logic.DAY), d90 = Logic.msToStr(Logic.toMs(today) - 90 * Logic.DAY);
      t.params.forEach((p) => {
        const pts = es.filter((e) => e.values && e.values[p.key] != null).map((e) => ({ date: e.date, v: Number(e.values[p.key]) }));
        const last = pts[pts.length - 1];
        const p30 = pts.filter((x) => x.date >= d30).map((x) => x.v), p90 = pts.filter((x) => x.date >= d90);
        const mean = p90.length ? p90.reduce((a, x) => a + x.v, 0) / p90.length : null;
        const slope = weeklySlope(p90);
        const st = last ? Logic.status(p, last.v) : 'na';
        L.push(`| ${p.label}${p.unit ? ` (${p.unit})` : ''} | ${last ? fmt(last.v, p.dp) : '—'} | ${last ? last.date : '—'} | ${fmt(p.low, p.dp)}–${fmt(p.high, p.dp)} | ${st === 'na' ? '—' : st} | ${p30.length ? `${fmt(Math.min(...p30), p.dp)}–${fmt(Math.max(...p30), p.dp)}` : '—'} | ${fmt(mean, p.dp)} | ${slope == null ? '—' : (slope >= 0 ? '+' : '') + fmt(slope, (p.dp ?? 2) + 1)} | ${p90.length} |`);
      });
      L.push('');
    }
    const recent = es.filter((e) => e.waterChange || e.gfo || (e.doses && Object.keys(e.doses).length) || (e.events && e.events.length) || e.note).slice(-15).reverse();
    if (recent.length) {
      L.push('Recent husbandry (newest first, last 15):', '');
      recent.forEach((e) => {
        const bits = [];
        if (e.waterChange) bits.push(`water change ${Logic.wcText(e.waterChange, Logic.entryWcGallons(ctx, e))}`);
        if (e.gfo) bits.push(`GFO ${e.gfo.grams != null ? fmt(e.gfo.grams, 0) + ' g' : 'replaced'}`);
        Object.entries(e.doses || {}).forEach(([k, v]) => { const d = (t.doses || []).find((x) => x.key === k); bits.push(`dosed ${d ? d.label : k} ${fmt(v)}${d && d.unit ? ' ' + d.unit : ''}`); });
        (e.events || []).forEach((ev) => bits.push(Logic.evText(ev)));
        if (e.note) bits.push(`note: ${e.note.replace(/\s+/g, ' ')}`);
        L.push(`- ${e.date}: ${bits.join('; ')}`);
      });
      L.push('');
    }
  });

  if (state.filters.length) {
    L.push('## RODI filters', '');
    L.push('| Stage | Installed | Days | Gallons | Used | Status | Projected due |');
    L.push('|---|---|---|---|---|---|---|');
    [...state.filters].sort((a, b) => (a.order || 0) - (b.order || 0)).forEach((f) => {
      const u = Logic.filterUsage(ctx, f);
      L.push(u ? `| ${f.name} | ${f.installed} | ${u.days} | ${fmt(u.gal, 0)} (${f.basis}) | ${Math.round(u.pct * 100)}% | ${u.st} | ${u.due ? Logic.msToStr(u.due) : '—'} |`
        : `| ${f.name} | not set | — | — | — | — | — |`);
    });
    L.push('');
  }
  return L.join('\n');
}

/** All synced files as { path: text }. Deterministic for a given state and date. */
function buildFiles(state, today) {
  const cfg = state.config || Logic.DEFAULT_CONFIG;
  const ctx = { config: cfg, entries: state.entries, rodiLogs: state.rodi, today };
  const tanks = Object.fromEntries(cfg.tanks.map((t) => [t.id, t]));
  const entries = [...state.entries].sort((a, b) => byDate(a, b) || String(a.tank).localeCompare(String(b.tank)) || String(a.id).localeCompare(String(b.id)));

  const params = [], doses = [], maint = [];
  for (const e of entries) {
    const t = tanks[e.tank];
    const tName = t ? t.name : e.tank;
    for (const [k, v] of Object.entries(e.values || {})) {
      const p = t && t.params.find((x) => x.key === k);
      params.push([e.date, tName, k, p ? p.label : k, p ? p.unit : '', v, p ? p.low : '', p ? p.high : '', p ? Logic.status(p, Number(v)) : '']);
    }
    for (const [k, v] of Object.entries(e.doses || {})) {
      const d = t && (t.doses || []).find((x) => x.key === k);
      doses.push([e.date, tName, k, d ? d.label : k, d ? d.unit : '', v]);
    }
    if (e.waterChange) maint.push([e.date, tName, 'water_change', Logic.entryWcGallons(ctx, e), e.waterChange.percent, '', '']);
    if (e.gfo) maint.push([e.date, tName, 'gfo', '', '', e.gfo.grams, '']);
    for (const ev of e.events || []) maint.push([e.date, tName, ev.type || 'event', ev.gallons, ev.percent, ev.grams, Logic.evText(ev)]);
    if (e.note) maint.push([e.date, tName, 'note', '', '', '', e.note]);
  }
  const rodi = [...state.rodi].sort((a, b) => byDate(a, b) || String(a.id).localeCompare(String(b.id)))
    .map((l) => [l.date, l.source || 'manual', round(l.gallons, 2), l.tdsIn, l.tdsOut, l.note || '']);
  const filters = [...state.filters].sort((a, b) => (a.order || 0) - (b.order || 0)).map((f) => {
    const u = Logic.filterUsage(ctx, f);
    return [f.id, f.name, f.basis, f.lifeDays, f.lifeGallons, f.installed, u ? u.days : '', u ? round(u.gal, 1) : '', u ? Math.round(u.pct * 100) : '', u ? u.st : '', u && u.due ? Logic.msToStr(u.due) : '', (f.history || []).length];
  });
  const exp = { config: state.config, entries: state.entries, filters: state.filters, rodi: state.rodi };

  return {
    'digest.md': digest(state, today),
    'parameters.csv': csv(['date', 'tank', 'param', 'label', 'unit', 'value', 'target_low', 'target_high', 'status'], params),
    'doses.csv': csv(['date', 'tank', 'product', 'label', 'unit', 'amount'], doses),
    'maintenance.csv': csv(['date', 'tank', 'type', 'gallons', 'percent', 'grams', 'text'], maint),
    'rodi_log.csv': csv(['date', 'source', 'gallons', 'tds_in', 'tds_out', 'note'], rodi),
    'filters.csv': csv(['id', 'name', 'basis', 'life_days', 'life_gallons', 'installed', 'days_in_use', 'gallons', 'pct_used', 'status', 'projected_due', 'past_installs'], filters),
    'export.json': JSON.stringify(exp, null, 1) + '\n',
  };
}

/* ------------------------------------------------------------- GitHub push */
/**
 * Commit files to owner/repo@branch in one commit, keeping all other files.
 * Returns {committed:false} when the tree is unchanged.
 */
async function pushFiles({ repo, branch, token, dir, files, message, apiBase = 'https://api.github.com', fetchImpl = fetch }) {
  const gh = async (method, p, body) => {
    const r = await fetchImpl(`${apiBase}/repos/${repo}${p}`, {
      method,
      headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28', 'User-Agent': 'reef-tracker-sync', ...(body ? { 'Content-Type': 'application/json' } : {}) },
      body: body ? JSON.stringify(body) : undefined,
      signal: AbortSignal.timeout(30000),
    });
    const text = await r.text();
    let json = null; try { json = text ? JSON.parse(text) : null; } catch { /* not JSON */ }
    if (!r.ok) {
      const hint = r.status === 401 ? ' (token invalid or expired)'
        : r.status === 403 ? ' (token lacks Contents: read and write on this repo)'
        : r.status === 404 ? ' (repo or branch not found, or the token cannot see it)'
        : r.status === 409 ? ' (repository is empty: create it with a README first)' : '';
      throw new Error(`GitHub ${method} ${p}: HTTP ${r.status}${hint}${json && json.message ? ` — ${json.message}` : ''}`);
    }
    return json;
  };
  const ref = await gh('GET', `/git/ref/heads/${encodeURIComponent(branch)}`);
  const parent = await gh('GET', `/git/commits/${ref.object.sha}`);
  const prefix = dir ? dir.replace(/^\/+|\/+$/g, '') + '/' : '';
  const tree = await gh('POST', '/git/trees', {
    base_tree: parent.tree.sha,
    tree: Object.entries(files).map(([p, content]) => ({ path: prefix + p, mode: '100644', type: 'blob', content })),
  });
  if (tree.sha === parent.tree.sha) return { committed: false };
  const commit = await gh('POST', '/git/commits', { message, tree: tree.sha, parents: [ref.object.sha] });
  await gh('PATCH', `/git/refs/heads/${encodeURIComponent(branch)}`, { sha: commit.sha });
  return { committed: true, sha: commit.sha };
}

/* ------------------------------------------------------------- scheduler */
/**
 * opts: { repo, token, branch, dir, debounceMs, hour, tz, readState, getVersion, getMeta, setMeta, log }
 * Call changed() after every data change; it pushes debounceMs after the last change.
 * A daily run at `hour` refreshes the digest (filter ages, alerts) even without changes.
 */
function createSyncer(opts) {
  const o = Object.assign({ branch: 'main', dir: '', debounceMs: 10 * 60 * 1000, hour: 3, log: console }, opts);
  const enabled = Boolean(o.repo && o.token);
  const configError = o.repo && !REPO_RE.test(o.repo) ? 'GITHUB_SYNC_REPO must look like owner/name' : o.repo && !o.token ? 'GITHUB_SYNC_TOKEN is not set' : !o.repo && o.token ? 'GITHUB_SYNC_REPO is not set' : null;
  let timer = null, running = null, rerun = false, lastError = null;

  async function run(reason) {
    if (!enabled || configError) return { ok: false, error: configError || 'Sync not configured' };
    if (running) { rerun = true; return running; }
    running = (async () => {
      const version = o.getVersion();
      const today = Logic.todayIn(o.tz);
      try {
        const files = buildFiles(o.readState(), today);
        const r = await pushFiles({ repo: o.repo, branch: o.branch, token: o.token, dir: o.dir, files, message: `Reef Tracker sync ${today} (data v${version}, ${reason})`, apiBase: o.apiBase, fetchImpl: o.fetchImpl });
        o.setMeta('syncVersion', String(version));
        o.setMeta('syncAt', new Date().toISOString());
        o.setMeta('syncDay', today);
        if (r.committed) o.setMeta('syncSha', r.sha);
        lastError = null;
        o.log.log(`GitHub sync (${reason}): ${r.committed ? 'committed ' + r.sha.slice(0, 7) : 'no changes'}`);
        return { ok: true, ...r };
      } catch (e) {
        lastError = { at: new Date().toISOString(), message: e.message };
        o.log.error(`GitHub sync (${reason}) failed: ${e.message}`);
        return { ok: false, error: e.message };
      } finally {
        running = null;
        if (rerun) { rerun = false; changed(); }
      }
    })();
    return running;
  }
  function changed() {
    if (!enabled || configError) return;
    clearTimeout(timer);
    timer = setTimeout(() => { timer = null; run('after changes'); }, o.debounceMs);
    timer.unref?.();
  }
  function tick() {
    if (!enabled || configError) return;
    const hour = Number(new Intl.DateTimeFormat('en-CA', { timeZone: o.tz, hour: '2-digit', hourCycle: 'h23' }).format(new Date()));
    const today = Logic.todayIn(o.tz);
    if (hour === o.hour && o.getMeta('syncDay') !== today) run('daily');
    // Catch up after a restart or a failed push: data changed since the last good sync.
    else if (!timer && !running && o.getMeta('syncVersion') !== String(o.getVersion())) changed();
  }
  function status() {
    return {
      configured: enabled && !configError, error: configError, repo: o.repo || null, branch: o.branch, dir: o.dir || '',
      lastSyncAt: o.getMeta('syncAt'), lastSha: o.getMeta('syncSha'), syncedVersion: Number(o.getMeta('syncVersion') || 0) || null,
      pending: enabled && !configError && o.getMeta('syncVersion') !== String(o.getVersion()), lastError,
    };
  }
  return { run, changed, tick, status, enabled: enabled && !configError };
}

module.exports = { buildFiles, pushFiles, createSyncer, FILES, weeklySlope, csvCell };
